const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.LENTERA_PLAYWRIGHT_PATH || 'playwright');

(async () => {
  const browser = await chromium.launch({ channel: 'chromium' });
  try {
    const base = process.env.LENTERA_BASE_URL || 'http://127.0.0.1:8000';
    const stamp = Date.now();
    const name = 'L2 sintetis QA ' + stamp;
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(base + '/masuk');
    assert(await page.getByText('Lingkungan contoh').count(), 'Refusing outside demo environment');
    await page.getByLabel('Email', { exact: true }).fill('pengelola@example.test');
    await page.getByLabel('Kata sandi', { exact: true }).fill('Lentera-Demo-2026!');
    await page.getByRole('button', { name: 'Masuk', exact: true }).click();
    await page.waitForURL('**/beranda');
    await page.getByRole('link', { name: 'Instrumen L2', exact: true }).click();
    await page.getByRole('link', { name: 'Buat instrumen L2', exact: true }).click();
    await page.getByLabel('Jumlah soal', { exact: true }).fill('3');
    await page.getByRole('button', { name: 'Siapkan formulir', exact: true }).click();
    await page.getByLabel('Nama instrumen L2', { exact: true }).fill(name);
    await page.getByLabel('Petunjuk tes (opsional)', { exact: true }).fill('Instrumen sintetis untuk memeriksa alur, bukan tes resmi.');
    for (let i = 0; i < 3; i++) {
      await page.getByLabel('Teks soal ' + (i + 1), { exact: true }).fill('Pertanyaan L2 QA ' + stamp + ' nomor ' + (i + 1));
      for (let j = 0; j < 4; j++) await page.getByLabel('Soal ' + (i + 1) + ' · opsi ' + String.fromCharCode(65 + j), { exact: true }).fill('Jawaban sintetis ' + String.fromCharCode(65 + j));
      await page.getByLabel('Kunci soal ' + (i + 1), { exact: true }).selectOption(String(i));
    }
    await page.getByRole('button', { name: 'Simpan draf L2', exact: true }).click();
    await page.getByRole('button', { name: 'Terbitkan L2 versi 1', exact: true }).waitFor();
    const instrumentURL = page.url();
    const instrumentID = instrumentURL.split('/').pop();
    await page.getByRole('button', { name: 'Terbitkan L2 versi 1', exact: true }).click();
    await page.getByRole('button', { name: 'Buat draf versi L2 baru', exact: true }).waitFor();
    await page.getByRole('link', { name: 'Kelola kegiatan', exact: true }).click();
    await page.getByRole('link', { name: /^Kelola kegiatan:/ }).first().click();
    await page.getByRole('link', { name: 'Tambah sesi', exact: true }).click();
    await page.getByLabel('Nama sesi', { exact: true }).fill('Sesi L2 sintetis QA ' + stamp);
    await page.getByLabel('Nama narasumber', { exact: true }).fill('Narasumber L2 QA');
    await page.getByLabel('Versi instrumen L1', { exact: true }).selectOption({ index: 1 });
    const date = d => new Date(Date.now() + d * 86400000 + 7 * 3600000).toISOString().slice(0, 16);
    for (const [field, value] of Object.entries({ starts_at: date(0), join_opens_at: date(-1), join_closes_at: date(1), l1_opens_at: date(-1), l1_closes_at: date(1) })) await page.locator('[name=' + field + ']').fill(value);
    await page.getByRole('button', { name: 'Simpan sesi', exact: true }).click();
    await page.getByRole('button', { name: 'Aktifkan akses kelas', exact: true }).click();
    await page.getByRole('link', { name: 'Lihat QR dan tautan', exact: true }).waitFor();
    const sessionEditURL = page.url();
    await page.getByRole('link', { name: 'Atur evaluasi L2', exact: true }).click();
    const settingsURL = page.url();
    await page.getByLabel('Versi instrumen L2', { exact: true }).selectOption(instrumentID);
    for (const [field, value] of Object.entries({ pre_opens_at: date(-1), pre_closes_at: date(1), post_opens_at: date(-1), post_closes_at: date(1) })) await page.locator('[name=' + field + ']').fill(value);
    await page.getByLabel('Status akses L2', { exact: true }).selectOption('1');
    await page.getByLabel('Wajib pretest final sebelum post-test', { exact: true }).selectOption('1');
    await page.getByRole('button', { name: 'Simpan pengaturan L2', exact: true }).click();
    await page.getByText('Pengaturan L2 tersimpan. Peserta tetap mengikuti jadwal yang ditetapkan.', { exact: true }).waitFor();
    await page.goto(sessionEditURL);
    await page.getByRole('link', { name: 'Lihat QR dan tautan', exact: true }).click();
    const joinURL = await page.getByLabel('Tautan peserta').inputValue();
    const guestContext = await browser.newContext();
    const guest = await guestContext.newPage();
    guest.on('pageerror', error => errors.push(error.message));
    await guest.goto(joinURL);
    for (const [field, value] of Object.entries({ full_name: 'Peserta L2 QA ' + stamp, institution_name: 'Institusi QA', identity_number: '000123', department: 'Ekonomi', faculty: 'Ekonomi', phone: '08123456789', participant_category: 'Mahasiswa', email: 'l2-qa@example.test' })) await guest.locator('[name=' + field + ']').fill(value);
    await guest.getByRole('button', { name: 'Gabung kelas', exact: true }).click();
    await guest.getByRole('link', { name: 'Buka post-test', exact: true }).click();
    assert.equal(await guest.getByRole('button', { name: 'Mulai post-test', exact: true }).count(), 0);
    await guest.goto(joinURL + '/l2/pre');
    assert.equal(await guest.getByText('Pertanyaan L2 QA ' + stamp + ' nomor 1', { exact: false }).count(), 0);
    const csrf = await guest.locator('form [name=_token]').inputValue();
    const badCsrf = await guest.request.post(joinURL + '/l2/pre/start', { headers: { 'Sec-Fetch-Site': 'cross-site' }, form: { _token: 'invalid' }, maxRedirects: 0 });
    assert.equal(badCsrf.status(), 419);
    await guest.getByRole('button', { name: 'Mulai pretest', exact: true }).click();
    await guest.locator('#l2-0-0').check();
    await guest.getByRole('button', { name: 'Simpan draf', exact: true }).click();
    await guest.getByText('Draf jawaban tersimpan di server.', { exact: true }).waitFor();
    await guest.reload();
    assert(await guest.locator('#l2-0-0').isChecked());
    const stale = await guest.request.post(joinURL + '/l2/pre/save', { headers: { Accept: 'application/json' }, form: { _token: csrf, revision: '1', 'answers[0]': '3' } });
    assert.equal(stale.status(), 422);
    const body = await guest.content();
    assert(!body.includes('"correct"') && !body.includes('instrument_snapshot') && !body.includes('Kunci:'), 'Answer key leaked');
    const outputs = path.join(__dirname, 'outputs', 'l2');
    fs.mkdirSync(outputs, { recursive: true });
    for (const width of [375, 768, 1440]) {
      await guest.setViewportSize({ width, height: 1000 });
      assert(await guest.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Exam overflow at ' + width);
      assert((await guest.locator('.rating-option').first().boundingBox()).height >= 44);
      await guest.screenshot({ path: path.join(outputs, 'exam-' + width + '.png'), fullPage: true });
    }
    await guest.locator('#l2-1-1').check();
    await guest.locator('#l2-2-3').check();
    await guest.getByRole('button', { name: 'Kirim final', exact: true }).click();
    await guest.getByRole('heading', { name: 'Pretest sudah dikirim.', exact: true }).waitFor();
    assert(!(await guest.content()).includes('66,67'));
    const retry = await guest.request.post(joinURL + '/l2/pre/submit', { form: { _token: csrf, 'answers[0]': '3' }, maxRedirects: 0 });
    assert.equal(retry.status(), 302);
    await guest.goto(joinURL + '/l2/post');
    await guest.getByRole('button', { name: 'Mulai post-test', exact: true }).click();
    for (let i = 0; i < 3; i++) await guest.locator('#l2-' + i + '-' + i).check();
    await guest.getByRole('button', { name: 'Kirim final', exact: true }).click();
    await guest.getByRole('heading', { name: 'Post-test sudah dikirim.', exact: true }).waitFor();
    assert(!(await guest.content()).includes('100,00'));
    await page.goto(settingsURL);
    assert(await page.getByText('Pasangan lengkap: 1', { exact: false }).count());
    assert.equal(await page.locator('input[name=l2_instrument_id]').inputValue(), instrumentID);
    await page.getByLabel('Tampilkan skor kepada peserta', { exact: true }).selectOption('1');
    await page.getByRole('button', { name: 'Simpan pengaturan L2', exact: true }).click();
    await page.getByText('Pengaturan L2 tersimpan. Peserta tetap mengikuti jadwal yang ditetapkan.', { exact: true }).waitFor();
    await guest.reload();
    assert(await guest.getByText('Skor Anda: 100,00 / 100.', { exact: true }).count());
    assert(await guest.getByText('Selisih post-test minus pretest Anda: 33,33 poin persentase.', { exact: true }).count());
    const otherContext = await browser.newContext();
    assert.equal((await otherContext.request.post(joinURL + '/l2/pre/submit', { form: { _token: csrf }, maxRedirects: 0 })).status(), 419);
    const otherPage = await otherContext.newPage();
    await otherPage.goto(joinURL + '/l2/pre');
    assert.equal(otherPage.url(), joinURL);
    await otherContext.close();
    await page.goto(instrumentURL);
    await page.getByRole('button', { name: 'Buat draf versi L2 baru', exact: true }).click();
    await page.getByRole('button', { name: 'Terbitkan L2 versi 2', exact: true }).waitFor();
    await page.getByLabel('Kunci soal 1', { exact: true }).selectOption('3');
    await page.getByRole('button', { name: 'Simpan perubahan L2', exact: true }).click();
    await page.getByText('Perubahan draf L2 tersimpan.', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Terbitkan L2 versi 2', exact: true }).click();
    await page.getByRole('button', { name: 'Buat draf versi L2 baru', exact: true }).waitFor();
    await guest.goto(joinURL + '/l2/pre');
    assert(await guest.getByText('Skor Anda: 66,67 / 100.', { exact: true }).count());
    assert.equal(errors.length, 0, errors.join('\n'));
    console.log(JSON.stringify({ passed: true, flow: 'L2 authoring → assignment → QR guest → pre draft/final → post final → release → paired scores → V2 isolation', serverScores: [66.67, 100], delta: 33.33, keyNotRendered: true, staleChecked: true, retryChecked: true, csrfChecked: true, widths: [375, 768, 1440], errors }));
    await guestContext.close();
  } finally {
    await browser.close();
  }
})().catch(error => { console.error(error); process.exit(1); });
